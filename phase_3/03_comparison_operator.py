print(saved_pin == entered_pin)



registered_email = "abc@gmail.com"
entered_email = "xyz@gmail.com"
print(registered_email == entered_email)

'''2️⃣ Not Equal To (`!=`)
Checks whether two values are different.'''


print(10 != 5)

print(20 != 20)

username = "admin"
print(username != "guest")


expected_price = 999
actual_price = 1099
print(expected_price != actual_price)



registered_email = "abc@gmail.com"
